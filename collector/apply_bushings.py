def fit_lines(card):
    """Читаемые строки совместимости из строк подбора: «Brand Model (2010–2017)»."""
    brands = next((c["values"] for c in card["complex_attributes"] if c.get("complex_id") == 100003 and c.get("id") == 22916), [])
    models = next((c["values"] for c in card["complex_attributes"] if c.get("complex_id") == 100003 and c.get("id") == 22917), [])
    groups = {}
    for b, m in zip(brands, models):
        base = re.split(r",| \(", m["value"])[0]
        yrs = re.findall(r"\((\d{4}) - (\d{4}|по н\.в\.)\)", m["value"])
        g = groups.setdefault((b["value"], base), [9999, 0, False])
        for y1, y2 in yrs:
            g[0] = min(g[0], int(y1))
            if y2.startswith("по"): g[2] = True
            else: g[1] = max(g[1], int(y2))
    out = []
    for (b, m), (y1, y2, now) in groups.items():
        rng = f" ({y1}–{'н.в.' if now else y2})" if y1 != 9999 else ""
        out.append(f"{b} {m}{rng}")
    return out


