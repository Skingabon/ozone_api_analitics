def main(apply):
    offers = list(TEXTS)
    live, prices = A.live_cards(offers)
    items = []
    for o in offers:
        assert len(TEXTS[o]) < 6000, (o, len(TEXTS[o]))
        it = A.build(live[o], {}, prices[o])
        A.setv(it["attributes"], 4191, TEXTS[o])
        old_tags = next((a["values"][0]["value"] for a in it["attributes"] if a["id"] == 23171), "")
        if o == "Uplotnitel_50":
            A.setv(it["attributes"], 23171, UPL_TAGS); it["name"] = UPL_NAME
            A.setv(it["attributes"], 4180, UPL_NAME)
            # в словаре «Материал корпуса» нет TPU: ближайший допустимый вариант «Пластик» (вместо ошибочного «Силикон»)
            s2, r2 = A.call("/v1/description-category/attribute/values/search", {"attribute_id": 22011, "description_category_id": 17027928, "type_id": 99447, "value": "Пластик", "limit": 5})
            pl = next(x for x in r2["result"] if x["value"] == "Пластик")
            A.setv(it["attributes"], 22011, "Пластик", pl["id"])
        else:
            A.setv(it["attributes"], 23171, A.merge_tags(TAGS_EXTRA[o], old_tags))
        if o == "VT_CheryTigg07pro":
            A.setv(it["attributes"], 6606, "17"); A.setv(it["attributes"], 4383, "20")
        print(f"{o[:26]:26} описание {len(TEXTS[o])} симв.")
        items.append(it)
    if not apply:
        print("\nПревью Polo-sedan:\n" + re.sub(r"<br/>", "\n", re.sub(r"</?(ul|li|b)>", "", TEXTS["Polo-sedan"]))[:1500]); print("DRY-RUN"); return
    s, r = A.call("/v3/product/import", {"items": items}); print("import", s, r)
    if s == 200:
        for i in A.wait(r["result"]["task_id"]): print(i["offer_id"], i["status"], [e.get("description", "")[:100] for e in i.get("errors", [])])
        time.sleep(5); A.restore_prices(offers, prices)


